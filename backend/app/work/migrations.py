"""Versioned schema of `work.sqlite3` (M6).

Each migration is an ordered list of complete SQL statements applied in ONE transaction together with
`PRAGMA user_version = <version>` and a row in `work_schema_migrations` (name + checksum). Migrations are
append-only: a released migration is never edited (its checksum is verified on start); a change is a new version.

Portability: plain `CREATE TABLE`/`CREATE INDEX` with TEXT ids generated by the application, ISO-8601 TEXT dates and
UTC timestamps, CHECK constraints and foreign keys. The SQLite-specific parts are named here so a PostgreSQL port
replaces only them: `INTEGER PRIMARY KEY AUTOINCREMENT` (→ `BIGSERIAL`/identity), the append-only triggers
(→ a trigger function or REVOKE UPDATE/DELETE), `PRAGMA user_version` (→ the `work_schema_migrations` table alone).
Domain logic never uses SQLite-only SQL (no `INSERT OR REPLACE`, no JSON1 queries).

Rollback: migrations are additive. Before migrating an existing database the runner writes a consistent backup
(`work.sqlite3.pre-v<N>-<UTC>.bak`, SQLite online backup API — includes WAL content); rollback = stop the backend,
restore that file (`python -m app.tools.work_db restore`), start the previous application version.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass


@dataclass(frozen=True)
class Migration:
    version: int
    name: str
    statements: tuple[str, ...]

    @property
    def checksum(self) -> str:
        return hashlib.sha256("\n;\n".join(self.statements).encode("utf-8")).hexdigest()


