  await list.getByRole("link", { name: /Спецификация датасета/ }).click();
  await expect(page).toHaveURL(/\/templates\/dataset_spec$/);
  await expect(page.getByRole("heading", { name: "Структура документа" })).toBeVisible();
  await expect(page.getByText("обязательный").first()).toBeVisible();

  await page.getByRole("button", { name: "Создать с ИИ" }).click();
  await page.getByLabel(/^Название \(необязательно\)/).fill("Датасет клиентских карточек T-01");
  await page.getByLabel(/^Что должно быть в документе/).fill("Опиши датасет клиентских карточек из CRM для витрины метрик");
  await page.getByRole("button", { name: "Предложить черновик" }).click();
  const card = page.locator(".ai-proposal");
  await expect(card).toContainText("Черновик по запросу");
  await expect(card).toContainText("Предложение");
  await expect(card.locator(".ai-todo")).toContainText("TODO"); // missing facts are marked, not invented
